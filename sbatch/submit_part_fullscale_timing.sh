#!/usr/bin/env bash
# Isolated sustained diagnostic: never changes the production submission graph.
set -euo pipefail
repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
campaign= dry_run=0 train_steps=10000 validation_steps=2500 budget_minutes=100
account=reu-aisocial partition=tigris
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 2; }
usage() {
  cat <<'USAGE'
Usage: bash sbatch/submit_part_fullscale_timing.sh --campaign DIR [options]

Queue one isolated sustained timing diagnostic against an existing frozen
campaign. Production jobs, submission ledgers, benchmarks, and checkpoints are
never changed. Results go into a new campaign/diagnostics/timing.* directory.

  --campaign DIR          Existing prepared full-scale campaign (required).
  --train-steps N         Requested sustained training steps per model (10000).
  --validation-steps N    Requested validation-only steps per model (2500).
  --budget-minutes N      Driver's total soft budget, 1..100 minutes (100).
  --account NAME          Slurm account (reu-aisocial).
  --partition NAME        Slurm partition (tigris).
  --dry-run               Read-only validation and resource preview; no writes.

Allocation is fixed: 1 node, 1 GPU, 1 task, 8 CPUs, 128G, 02:00:00, USR1@300.
No dependencies, arrays, cancellation, production resume, or environment installs.
The current diagnostic driver/worker are copied and checksummed independently;
all recipe/model/data code and Python come from the existing pinned campaign.
USAGE
}
while (( $# )); do
  case "$1" in
    --help|-h) usage; exit 0 ;;
    --dry-run) dry_run=1; shift ;;
    --campaign|--train-steps|--validation-steps|--budget-minutes|--account|--partition)
      (( $# >= 2 )) || fail "Missing value for $1"
      case "$1" in
        --campaign) campaign=$2 ;;
        --train-steps) train_steps=$2 ;;
        --validation-steps) validation_steps=$2 ;;
        --budget-minutes) budget_minutes=$2 ;;
        --account) account=$2 ;;
        --partition) partition=$2 ;;
      esac
      shift 2 ;;
    *) fail "Unknown option: $1" ;;
  esac
done
[[ -n "$campaign" ]] || fail '--campaign is required'
for value in "$train_steps" "$validation_steps" "$budget_minutes"; do
  [[ "$value" =~ ^[1-9][0-9]{0,8}$ ]] || fail 'Steps and budget must be positive integers (at most nine digits)'
done
(( budget_minutes <= 100 )) || fail '--budget-minutes must be at most 100'
(( train_steps <= 20000 )) || fail '--train-steps must be at most 20000'
(( validation_steps <= 2500 )) || fail '--validation-steps must be at most 2500'
[[ "$account" =~ ^[a-zA-Z0-9_-]+$ && "$partition" =~ ^[a-zA-Z0-9_-]+$ ]] || fail 'Invalid account or partition'
for command in realpath sha256sum; do
  command -v "$command" >/dev/null || fail "Missing command: $command"
done
campaign="$(realpath -e -- "$campaign")" || fail 'Campaign does not exist'
[[ -d "$campaign/source" && -f "$campaign/launch.env" && -f "$campaign/source.sha256" && -f "$campaign/campaign.json" ]] || fail 'Expected a prepared campaign with source, launch.env, source.sha256, and campaign.json'
[[ -f "$repo_root/scripts/diagnose_part_fullscale_timing.py" && -f "$repo_root/sbatch/run_part_fullscale_timing.sh" ]] || fail 'Diagnostic source is missing; update the repository first'
(
  cd -- "$campaign/source"
  sha256sum --quiet -c "$campaign/source.sha256"
) || fail 'Original campaign source checksum verification failed'
# This trusted campaign configuration was generated by its original submitter.
# shellcheck disable=SC1090
source "$campaign/launch.env"
[[ "${PART_FULLSCALE_PYTHON:-}" == /* && -x "$PART_FULLSCALE_PYTHON" ]] || fail 'Pinned campaign Python must be an existing absolute executable'
if [[ -e "$campaign/diagnostics" || -L "$campaign/diagnostics" ]]; then
  [[ -d "$campaign/diagnostics" && ! -L "$campaign/diagnostics" ]] || fail 'Campaign diagnostics must be a real directory, not a symlink'
fi
if (( dry_run )); then
  printf 'Dry run: campaign=%s account=%s partition=%s\n' "$campaign" "$account" "$partition"
  printf 'Timing: train-steps=%s validation-steps=%s budget-minutes=%s\n' "$train_steps" "$validation_steps" "$budget_minutes"
  printf 'Resources: --nodes=1 --ntasks=1 --ntasks-per-node=1 --gpus-per-node=1 --cpus-per-task=8 --mem=128G --time=02:00:00 --signal=USR1@300\n'
  printf 'Results: %s/diagnostics/timing.<UTC>.<unique>/report.{json,md}\n' "$campaign"
  printf 'Nothing created, submitted, cancelled, or deleted; production queue and campaign artifacts are unchanged.\n'
  exit 0
fi
for command in sbatch mktemp cp; do
  command -v "$command" >/dev/null || fail "Missing command: $command"
done
# Inherited scheduler options must not introduce dependencies or change resources.
for option_name in ${!SBATCH_@}; do unset "$option_name"; done
umask 077
[[ -d "$campaign/diagnostics" ]] || mkdir -- "$campaign/diagnostics"
output="$(mktemp -d "$campaign/diagnostics/timing.$(date -u +%Y%m%dT%H%M%SZ).XXXXXX")"
mkdir -- "$output/source" "$output/source/scripts" "$output/source/sbatch" "$output/logs"
cp -- "$repo_root/scripts/diagnose_part_fullscale_timing.py" "$output/source/scripts/"
cp -- "$repo_root/sbatch/run_part_fullscale_timing.sh" "$output/source/sbatch/"
{
  printf 'PART_FULLSCALE_TIMING_CAMPAIGN=%q\n' "$campaign"
  printf 'PART_FULLSCALE_TIMING_TRAIN_STEPS=%q\n' "$train_steps"
  printf 'PART_FULLSCALE_TIMING_VALIDATION_STEPS=%q\n' "$validation_steps"
  printf 'PART_FULLSCALE_TIMING_BUDGET_MINUTES=%q\n' "$budget_minutes"
} > "$output/launch.env"
(
  cd -- "$campaign"
  sha256sum launch.env source.sha256 campaign.json
) > "$output/campaign.sha256"
(
  cd -- "$output"
  sha256sum launch.env campaign.sha256 source/scripts/diagnose_part_fullscale_timing.py source/sbatch/run_part_fullscale_timing.sh
) > "$output/diagnostic.sha256"
export PART_FULLSCALE_TIMING_OUTPUT="$output"
response="$(sbatch --parsable "--account=$account" "--partition=$partition" \
  --job-name=parte_timing "--chdir=$output" "--output=$output/logs/%x_%j.out" "--error=$output/logs/%x_%j.err" \
  --export=ALL --nodes=1 --ntasks=1 --ntasks-per-node=1 --gpus-per-node=1 \
  --cpus-per-task=8 --mem=128G --time=02:00:00 --signal=USR1@300 \
  "$output/source/sbatch/run_part_fullscale_timing.sh")" || fail "Submission failed; diagnostic snapshot retained at $output. Inspect the queue before retrying"
job="${response%%;*}"
[[ "$job" =~ ^[0-9]+$ ]] || fail "Invalid sbatch response: $response. Snapshot: $output. Inspect the queue before retrying"
printf '%s\n' "$job" > "$output/submitted_job_id.txt"
printf 'Timing job: %s\nDiagnostic: %s\nResults: %s/report.json\nSummary: %s/report.md\nLogs: %s/logs/parte_timing_%s.{out,err}\n' "$job" "$output" "$output" "$output" "$output" "$job"
printf 'Queue: squeue -j %s\nRead summary after completion: cat %q\n' "$job" "$output/report.md"
printf 'Production jobs, source, benchmarks, checkpoints, and submission ledger were not changed.\n'
