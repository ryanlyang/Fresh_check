#!/usr/bin/env bash
# Validation-only graph, isolated from the original campaign and its checkpoints.
set -euo pipefail
repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
campaign= output= resume= dependency= dry_run=0
account=reu-aisocial partition=tigris concurrency=3 cpus=8 memory=32G time_limit=04:00:00
declare -A explicit=()
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 2; }
usage() {
  cat <<'USAGE'
Usage: bash sbatch/submit_part_fullscale_validation.sh --campaign DIR [--output DIR]
       bash sbatch/submit_part_fullscale_validation.sh --resume OUTPUT_DIR

Read-only evaluation of the six validation-selected checkpoints from an original
standard/Ranger campaign. No training or test jobs are submitted. Results live in
a NEW sibling directory; the original source, weights, data, and ledgers are not
modified. The driver verifies that all six training runs have finished.

  --campaign DIR       Existing original standard full-scale campaign (new run).
  --output DIR         New sibling output; default CAMPAIGN_validation_<UTC>.
  --resume DIR         Reuse this evaluation's frozen source/configuration/results.
                       All previously recorded jobs must be terminal first.
  --dependency IDS     Explicit afterok IDs for this attempt's prepare job.
  --concurrency N      Concurrent evaluation tasks, 1..6 (default 3).
  --cpus N             Evaluation CPUs (default 8).
  --mem SIZE           Evaluation memory (default 32G).
  --time HH:MM:SS       Evaluation walltime, strictly under six hours (04:00:00).
  --account NAME       reu-aisocial by default.
  --partition NAME     tigris by default.
  --dry-run            Read-only source/configuration checks and resource preview.

Graph: CPU prepare (30min, 4CPU/16G) -> six 1GPU evaluations -> CPU report (1h,
4CPU/32G), all afterok. Resume never cancels jobs and cannot change frozen paths
or resources. Dependencies may be supplied anew for a retry; none is implicit.
Reports: OUTPUT/reports/validation_report.{json,md}
USAGE
}
while (( $# )); do
  case "$1" in
    --help|-h) usage; exit 0 ;;
    --dry-run) dry_run=1; shift ;;
    --campaign|--output|--resume|--dependency|--concurrency|--cpus|--mem|--time|--account|--partition)
      (( $# >= 2 )) || fail "Missing value for $1"
      explicit["$1"]=1
      case "$1" in
        --campaign) campaign=$2 ;; --output) output=$2 ;; --resume) resume=$2 ;;
        --dependency) dependency=$2 ;; --concurrency) concurrency=$2 ;; --cpus) cpus=$2 ;;
        --mem) memory=$2 ;; --time) time_limit=$2 ;; --account) account=$2 ;; --partition) partition=$2 ;;
      esac
      shift 2 ;;
    *) fail "Unknown option: $1" ;;
  esac
done
[[ -n "$campaign" || -n "$resume" ]] || fail '--campaign is required for a new evaluation'
[[ "$concurrency" =~ ^[1-6]$ && "$cpus" =~ ^[1-9][0-9]{0,2}$ ]] || fail 'Concurrency must be 1..6 and CPUs a positive integer'
[[ "$account" =~ ^[a-zA-Z0-9_-]+$ && "$partition" =~ ^[a-zA-Z0-9_-]+$ ]] || fail 'Invalid account or partition'
[[ "$memory" =~ ^[1-9][0-9]*[KMGTP]?$ ]] || fail 'Invalid memory size'
[[ "$time_limit" =~ ^0[0-5]:[0-5][0-9]:[0-5][0-9]$ && "$time_limit" != 00:00:00 ]] || fail 'Evaluation walltime must be positive and strictly under six hours, HH:MM:SS'
[[ -z "$dependency" || "$dependency" =~ ^[0-9]+(:[0-9]+)*$ ]] || fail 'Dependency requires numeric IDs separated by colons'
for command in realpath sha256sum cmp; do command -v "$command" >/dev/null || fail "Missing command: $command"; done

if [[ -n "$resume" ]]; then
  resume="$(realpath -e -- "$resume")" || fail 'Resume output does not exist'
  [[ -z "$output" || "$(realpath -m -- "$output")" == "$resume" ]] || fail '--output differs from --resume'
  output="$resume"
  [[ -f "$output/validation.sha256" ]] || fail 'Not a frozen validation evaluation'
  (cd -- "$output"; sha256sum --quiet -c validation.sha256) || fail 'Validation snapshot checksum verification failed'
  # Generated by this launcher and authenticated above.
  source "$output/validation_launch.env"
  [[ "$PART_VALIDATION_OUTPUT" == "$output" ]] || fail 'Frozen evaluation output differs from --resume'
  [[ -z "$campaign" || "$(realpath -e -- "$campaign")" == "$PART_VALIDATION_CAMPAIGN" ]] || fail 'Campaign differs from frozen evaluation'
  campaign="$PART_VALIDATION_CAMPAIGN"
  for mapping in account:ACCOUNT partition:PARTITION concurrency:CONCURRENCY cpus:CPUS memory:MEMORY time_limit:TIME; do
    variable=${mapping%%:*}; frozen="PART_VALIDATION_${mapping#*:}"
    option="--$variable"
    [[ "$variable" != memory ]] || option=--mem
    [[ "$variable" != time_limit ]] || option=--time
    [[ -z "${explicit[$option]:-}" || "${!variable}" == "${!frozen}" ]] || fail "$option differs from frozen evaluation"
    printf -v "$variable" '%s' "${!frozen}"
  done
else
  campaign="$(realpath -e -- "$campaign")" || fail 'Campaign does not exist'
  [[ -n "$output" ]] || output="${campaign}_validation_$(date -u +%Y%m%dT%H%M%SZ)"
  [[ ! -L "$output" ]] || fail 'Output cannot be a symlink'
  output="$(realpath -m -- "$output")"
  [[ ! -e "$output" ]] || fail 'Output already exists; use --resume after inspecting its jobs'
fi
[[ "$output" != "$campaign" && "$(dirname -- "$output")" == "$(dirname -- "$campaign")" ]] || fail 'Validation output must be a separate sibling of the training campaign'
for file in campaign.json source.sha256 launch.env; do
  [[ -f "$campaign/$file" ]] || fail "Missing original campaign metadata: $file"
done
[[ -d "$campaign/source" ]] || fail 'Missing original campaign source'
if [[ -n "$resume" ]]; then
  (cd -- "$campaign"; sha256sum --quiet -c "$output/original.sha256") || fail 'Original campaign metadata changed'
fi
(cd -- "$campaign/source"; sha256sum --quiet -c "$campaign/source.sha256") || fail 'Original source checksum verification failed'
unset PART_FULLSCALE_PYTHON PART_FULLSCALE_COMPARISON PART_FULLSCALE_TRAINING_RECIPE
source "$campaign/launch.env"
[[ "${PART_FULLSCALE_COMPARISON:-standard}" == standard && "${PART_FULLSCALE_TRAINING_RECIPE:-original}" == original ]] || fail 'Validation evaluation requires the original standard/Ranger campaign'
[[ "${PART_FULLSCALE_PYTHON:-}" == /* && -x "$PART_FULLSCALE_PYTHON" ]] || fail 'Pinned original Python is unavailable'
if [[ -n "$resume" ]]; then
  [[ "$PART_VALIDATION_PYTHON" == "$PART_FULLSCALE_PYTHON" ]] || fail 'Original Python differs from frozen evaluation'
else
  for relative in scripts/evaluate_part_fullscale_validation.py scripts/part_fullscale_validation_support.py sbatch/run_part_fullscale_validation.sh; do
    [[ -f "$repo_root/$relative" ]] || fail "Missing evaluation source: $relative"
  done
fi
if (( dry_run )); then
  printf 'Validation-only dry run: campaign=%s\nOutput: %s\n' "$campaign" "$output"
  printf 'Prepare: --nodes=1 --ntasks=1 --cpus-per-task=4 --mem=16G --time=00:30:00\n'
  printf 'Evaluate: --array=0-5%%%s --nodes=1 --ntasks=1 --gpus-per-node=1 --cpus-per-task=%s --mem=%s --time=%s\n' "$concurrency" "$cpus" "$memory" "$time_limit"
  printf 'Report: --nodes=1 --ntasks=1 --cpus-per-task=4 --mem=32G --time=01:00:00\n'
  [[ -z "$dependency" ]] || printf 'Prepare dependency: afterok:%s\n' "$dependency"
  printf 'Nothing created, submitted, cancelled, trained, or tested.\n'
  exit 0
fi
for command in sbatch squeue flock cp; do command -v "$command" >/dev/null || fail "Missing command: $command"; done
for option_name in ${!SBATCH_@}; do unset "$option_name"; done
unset CUDA_VISIBLE_DEVICES
export PYTHONNOUSERSITE=1 PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1
umask 077
if [[ -z "$resume" ]]; then
  mkdir -- "$output"
  mkdir -- "$output/source" "$output/source/scripts" "$output/source/sbatch" "$output/logs" "$output/original_metadata"
  cp -- "$repo_root/scripts/evaluate_part_fullscale_validation.py" "$repo_root/scripts/part_fullscale_validation_support.py" "$output/source/scripts/"
  cp -- "$repo_root/sbatch/run_part_fullscale_validation.sh" "$output/source/sbatch/"
  for file in campaign.json source.sha256 launch.env; do cp -- "$campaign/$file" "$output/original_metadata/"; done
  (cd -- "$output/original_metadata"; sha256sum campaign.json source.sha256 launch.env) > "$output/original.sha256"
  {
    printf 'PART_VALIDATION_CAMPAIGN=%q\n' "$campaign"
    printf 'PART_VALIDATION_OUTPUT=%q\n' "$output"
    printf 'PART_VALIDATION_PYTHON=%q\n' "$PART_FULLSCALE_PYTHON"
    printf 'PART_VALIDATION_ACCOUNT=%q\n' "$account"
    printf 'PART_VALIDATION_PARTITION=%q\n' "$partition"
    printf 'PART_VALIDATION_CONCURRENCY=%q\n' "$concurrency"
    printf 'PART_VALIDATION_CPUS=%q\n' "$cpus"
    printf 'PART_VALIDATION_MEMORY=%q\n' "$memory"
    printf 'PART_VALIDATION_TIME=%q\n' "$time_limit"
  } > "$output/validation_launch.env"
  (cd -- "$output"; sha256sum validation_launch.env original.sha256 \
    original_metadata/campaign.json original_metadata/source.sha256 original_metadata/launch.env \
    source/scripts/evaluate_part_fullscale_validation.py source/scripts/part_fullscale_validation_support.py \
    source/sbatch/run_part_fullscale_validation.sh) > "$output/validation.sha256"
fi
exec 9>"$output/submission.lock"
flock -n 9 || fail 'Another evaluation submitter owns this output'
if [[ -f "$output/submission_uncertain" ]]; then
  fail "Previous submission was interrupted/ambiguous; inspect queue and $output/submission_uncertain before manual recovery"
fi
if [[ -f "$output/submitted_job_ids.tsv" ]]; then
  live="$(squeue --noheader --user "$(id -un)" --format='%i')" || fail 'Cannot inspect live jobs; refusing duplicate submissions'
  while IFS=$'\t' read -r old_phase old_id _; do
    [[ "$old_id" =~ ^[0-9]+$ ]] || fail 'Invalid evaluation job ledger'
    while read -r active; do
      [[ "${active%%_*}" != "$old_id" ]] || fail "Evaluation $old_phase job $old_id is still live; nothing submitted or cancelled"
    done <<< "$live"
  done < "$output/submitted_job_ids.tsv"
fi
export PART_VALIDATION_OUTPUT="$output"
worker="$output/source/sbatch/run_part_fullscale_validation.sh"
submit() {
  local phase=$1 depends=$2 response job
  shift 2
  local deps=()
  [[ -z "$depends" ]] || deps=("--dependency=afterok:$depends" --kill-on-invalid-dep=yes)
  export PART_VALIDATION_PHASE="$phase"
  printf '%s\t%s\n' "$phase" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$output/submission_uncertain"
  response="$(sbatch --parsable "--account=$account" "--partition=$partition" \
    "--job-name=parte_val_${phase}" "--chdir=$output" "--output=$output/logs/%x_%A_%a.out" \
    "--error=$output/logs/%x_%A_%a.err" --export=ALL "${deps[@]}" "$@" "$worker")" || fail 'Submission failed; inspect the queue before retrying. Frozen evaluation retained.'
  job="${response%%;*}"
  [[ "$job" =~ ^[0-9]+$ ]] || fail "Invalid sbatch response: $response. Inspect the queue before retrying"
  printf '%s\t%s\t%s\n' "$phase" "$job" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$output/submitted_job_ids.tsv"
  rm -- "$output/submission_uncertain"
  printf '%s\n' "$job"
}
prepare_job="$(submit prepare "$dependency" --nodes=1 --ntasks=1 --cpus-per-task=4 --mem=16G --time=00:30:00)"
evaluate_job="$(submit evaluate "$prepare_job" --nodes=1 --ntasks=1 --ntasks-per-node=1 --gpus-per-node=1 \
  "--array=0-5%$concurrency" "--cpus-per-task=$cpus" "--mem=$memory" "--time=$time_limit")"
report_job="$(submit report "$evaluate_job" --nodes=1 --ntasks=1 --cpus-per-task=4 --mem=32G --time=01:00:00)"
printf 'Validation evaluation: %s\nPrepare job: %s\nEvaluation array: %s\nReport job: %s\n' "$output" "$prepare_job" "$evaluate_job" "$report_job"
printf 'Reports: %s/reports/validation_report.{json,md}\n' "$output"
printf 'Production campaign, training jobs, checkpoints, and test results were not changed.\n'
