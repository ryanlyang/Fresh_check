#!/usr/bin/env bash
# Submit a QCD-vs-Hgg DETR/free-slot reconstruction + five-view experiment.

set -euo pipefail
IFS=$'\n\t'

: "${PROJECT_DIR:=/home/ryreu/atlas/Fresh_check}"
SCRIPT_DIR="${PROJECT_DIR}/sbatch"
# shellcheck source=common.sh
source "${SCRIPT_DIR}/common.sh"

: "${DETR_SLOT_QCD_HGG_TAG:=$(date +%Y%m%d_%H%M%S)}"
: "${DETR_SLOT_QCD_HGG_HLT_DEGRADATION_STRENGTH:=0.6}"
DETR_SLOT_QCD_HGG_HLT_TAG="${DETR_SLOT_QCD_HGG_HLT_DEGRADATION_STRENGTH//./p}"
: "${DETR_SLOT_QCD_HGG_ROOT:=${OUTPUT_ROOT}/detr_slot_qcd_hgg_binary_hlt${DETR_SLOT_QCD_HGG_HLT_TAG}_${DETR_SLOT_QCD_HGG_TAG}}"

export DETR_SLOT_BINARY_ROOT="${DETR_SLOT_QCD_HGG_ROOT}"
export DETR_SLOT_BINARY_INPUT_ROOT="${DETR_SLOT_BINARY_ROOT}/binary_inputs"
export DETR_SLOT_TASK_NAME="QCD_vs_Hgg_DETR_free_slot"
export DETR_SLOT_SUBMISSION_NAME="detr_slot_qcd_hgg_binary_submission"
export DETR_SLOT_SOURCE_LABEL_NAMES="QCD Hgg"
export DETR_SLOT_BINARY_LABEL_FILTER="0 1"
export DETR_SLOT_HLT_DEGRADATION_STRENGTH="${DETR_SLOT_QCD_HGG_HLT_DEGRADATION_STRENGTH}"
export HLT_DEGRADATION_STRENGTH="${DETR_SLOT_QCD_HGG_HLT_DEGRADATION_STRENGTH}"

export DETR_SLOT_BINARY_MODEL_TRAIN_SIZE="${DETR_SLOT_QCD_HGG_MODEL_TRAIN_SIZE:-500000}"
export DETR_SLOT_BINARY_MODEL_VAL_SIZE="${DETR_SLOT_QCD_HGG_MODEL_VAL_SIZE:-150000}"
export DETR_SLOT_BINARY_STACK_TRAIN_SIZE="${DETR_SLOT_QCD_HGG_STACK_TRAIN_SIZE:-500000}"
export DETR_SLOT_BINARY_STACK_VAL_SIZE="${DETR_SLOT_QCD_HGG_STACK_VAL_SIZE:-150000}"
export DETR_SLOT_BINARY_FINAL_TEST_SIZE="${DETR_SLOT_QCD_HGG_FINAL_TEST_SIZE:-500000}"
export DETR_SLOT_BINARY_CACHE_MAX_JETS_PER_SPLIT="${DETR_SLOT_QCD_HGG_CACHE_MAX_JETS_PER_SPLIT:-${DETR_SLOT_BINARY_FINAL_TEST_SIZE}}"

export DETR_SLOT_BINARY_RECO_EPOCHS="${DETR_SLOT_QCD_HGG_RECO_EPOCHS:-30}"
export DETR_SLOT_BINARY_TAGGER_EPOCHS="${DETR_SLOT_QCD_HGG_TAGGER_EPOCHS:-45}"
export DETR_SLOT_OFFLINE_TEACHER_EPOCHS="${DETR_SLOT_QCD_HGG_OFFLINE_TEACHER_EPOCHS:-45}"
export DETR_SLOT_RECO_TIME="${DETR_SLOT_QCD_HGG_RECO_TIME:-2-12:00:00}"
export DETR_SLOT_TAGGER_TIME="${DETR_SLOT_QCD_HGG_TAGGER_TIME:-2-12:00:00}"
export DETR_SLOT_NUM_SLOTS="${DETR_SLOT_QCD_HGG_NUM_SLOTS:-160}"
export DETR_SLOT_EXPORT_MAX_TOKENS="${DETR_SLOT_QCD_HGG_EXPORT_MAX_TOKENS:-128}"
export DETR_SLOT_CACHE_EXPORT_MAX_TOKENS="${DETR_SLOT_EXPORT_MAX_TOKENS}"
export DETR_SLOT_MAX_TOKENS_PER_VIEW="${DETR_SLOT_EXPORT_MAX_TOKENS}"

fresh_prepare_submitter
if fresh_is_dry_run; then
  echo "DRY_RUN/PRINT_ONLY enabled; delegated submitter will print sbatch commands only." >&2
fi

cat <<SUMMARY
detr_slot_qcd_hgg_binary_wrapper:
  task: ${DETR_SLOT_TASK_NAME}
  root: ${DETR_SLOT_BINARY_ROOT}
  source_label_names: ${DETR_SLOT_SOURCE_LABEL_NAMES}
  hlt_degradation_strength: ${DETR_SLOT_HLT_DEGRADATION_STRENGTH}
  split_caps:
    model_train: ${DETR_SLOT_BINARY_MODEL_TRAIN_SIZE}
    model_val: ${DETR_SLOT_BINARY_MODEL_VAL_SIZE}
    stack_train: ${DETR_SLOT_BINARY_STACK_TRAIN_SIZE}
    stack_val: ${DETR_SLOT_BINARY_STACK_VAL_SIZE}
    final_test: ${DETR_SLOT_BINARY_FINAL_TEST_SIZE}
  model:
    reco_epochs: ${DETR_SLOT_BINARY_RECO_EPOCHS}
    reco_time: ${DETR_SLOT_RECO_TIME}
    tagger_epochs: ${DETR_SLOT_BINARY_TAGGER_EPOCHS}
    tagger_time: ${DETR_SLOT_TAGGER_TIME}
    num_slots: ${DETR_SLOT_NUM_SLOTS}
    export_max_tokens: ${DETR_SLOT_EXPORT_MAX_TOKENS}
SUMMARY

bash "${SCRIPT_DIR}/submit_detr_slot_qcd_tbqq_binary_experiment.sh"
