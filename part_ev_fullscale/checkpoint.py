"""Complete rank-aware restart state (trusted, locally generated checkpoints)."""
from __future__ import annotations

import copy
import os
from pathlib import Path
import random
import tempfile

import numpy as np
import torch


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed & 0xFFFFFFFF)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def capture_rank_state(model):
    return {"python": random.getstate(), "numpy": np.random.get_state(),
            "torch": torch.get_rng_state(),
            "cuda": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else [],
            "trimmers": {name: copy.deepcopy(module._counter)
                         for name, module in model.named_modules() if hasattr(module, "_counter")}}


def restore_rank_state(model, state):
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"].cpu())
    if torch.cuda.is_available():
        torch.cuda.set_rng_state_all([value.cpu() for value in state["cuda"]])
    modules = dict(model.named_modules())
    for name, value in state["trimmers"].items():
        modules[name]._counter = copy.deepcopy(value)


def atomic_torch_save(payload, path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as handle:
            torch.save(payload, handle)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def trusted_load(path):
    # Only campaign artifacts generated by this code, never arbitrary downloads.
    return torch.load(path, map_location="cpu", weights_only=False)
